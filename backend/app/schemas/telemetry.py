from pydantic import BaseModel, Field
from typing import Dict, List, Optional, Any
from enum import Enum
import time

class SystemState(str, Enum):
    NORMAL = "NORMAL"
    WATCH = "WATCH"
    WARNING = "WARNING"
    HIGH_RISK = "HIGH_RISK"
    CRITICAL = "CRITICAL"
    SENSOR_DEGRADED = "SENSOR_DEGRADED"
    CALIBRATING = "CALIBRATING"
    RECOVERY_CHECK = "RECOVERY_CHECK"
    HARD_LOCKOUT = "HARD_LOCKOUT"

class ProtectiveAction(str, Enum):
    NONE = "NONE"
    OBSERVE_LOG = "OBSERVE_LOG"
    DERATE_PWM_60 = "DERATE_PWM_60"
    DERATE_PWM_30 = "DERATE_PWM_30"
    EMERGENCY_SHUTDOWN = "EMERGENCY_SHUTDOWN"
    RAMP_PROBATION = "RAMP_PROBATION"
    MANUAL_RESET_REQUIRED = "MANUAL_RESET_REQUIRED"

class MotorState(str, Enum):
    STOPPED = "STOPPED"
    STARTING = "STARTING"
    RUNNING = "RUNNING"
    FAULT = "FAULT"
    UNKNOWN = "UNKNOWN"

class SensorDataSource(str, Enum):
    REAL = "REAL"
    FALLBACK = "FALLBACK"
    SIMULATED = "SIMULATED"

class SensorQualityStatus(str, Enum):
    OK = "OK"
    VALID = "OK"
    INITIALIZING = "INITIALIZING"
    DEGRADED = "DEGRADED"
    STALE = "STALE"
    DISCONNECTED = "DISCONNECTED"
    INVALID = "INVALID"
    OUT_OF_BOUNDS = "INVALID"
    CALIBRATION_REQUIRED = "CALIBRATION_REQUIRED"
    ERROR = "ERROR"
    SIMULATED = "SIMULATED"

class RawSensorFrame(BaseModel):
    sequence_id: int = Field(..., description="Monotonically increasing sequence number")
    timestamp_ms: int = Field(..., description="Device or simulation millisecond timestamp")
    
    # Primary Motor Current (ACS712)
    current_a: Optional[float] = Field(None, description="Motor current from ACS712 (Amperes)")
    current_raw_adc: Optional[int] = Field(None, description="Raw ADC count from ACS712 (0-1023)")
    current_v: Optional[float] = Field(None, description="Analog voltage from ACS712 (Volts)")
    
    # Motion & Vibration (MPU6050, mounted upside down)
    vibe_g: Optional[float] = Field(None, description="Vibration acceleration RMS from MPU6050 (gravity removed, g)")
    ax: Optional[float] = Field(None, description="Acceleration X axis (g)")
    ay: Optional[float] = Field(None, description="Acceleration Y axis (g)")
    az: Optional[float] = Field(None, description="Acceleration Z axis (g, approx -1.0g stationary upside down)")
    gx: Optional[float] = Field(None, description="Gyroscope X rate (deg/s)")
    gy: Optional[float] = Field(None, description="Gyroscope Y rate (deg/s)")
    gz: Optional[float] = Field(None, description="Gyroscope Z rate (deg/s)")
    
    # Stationary Obstacle Detection (IR sensor on D2, NOT RPM!)
    ir_object_detected: bool = Field(False, description="Whether stationary object/obstruction is detected")
    ir_raw_state: int = Field(1, description="Raw digital read from IR sensor pin D2 (0 or 1)")
    
    # Ambient Environmental Context (DHT11 on D4) - Room context ONLY, NOT motor temperature
    amb_temp_c: Optional[float] = Field(None, description="Ambient room temperature from DHT11 (deg C)")
    amb_hum_pct: Optional[float] = Field(None, description="Ambient relative humidity from DHT11 (%)")
    
    # Motor Actuation & State
    motor_pwm: int = Field(0, description="Motor PWM duty cycle command (0-255, starts at 0 for safe stopped startup)")
    commanded_motor_state: MotorState = Field(MotorState.STOPPED, description="Firmware-commanded motor state")
    inferred_motor_state: MotorState = Field(MotorState.STOPPED, description="Independently inferred physical motor state")
    
    # Telemetry provenance & active simulations
    source: SensorDataSource = Field(SensorDataSource.SIMULATED, description="Telemetry provenance: REAL, FALLBACK, or SIMULATED")
    is_simulated: bool = Field(False, description="Whether frame is generated by physics simulator or contains simulated faults")
    sensor_statuses: Dict[str, str] = Field(default_factory=dict, description="Status for individual sensors")
    active_faults: List[str] = Field(default_factory=list, description="Currently active injected fault modes")

    @property
    def mpu_orientation(self) -> str:
        """Dynamically infer MPU6050 physical mounting orientation from stationary gravity vector."""
        if self.az is None:
            return "UNKNOWN"
        if self.az > 0.5:
            return "NORMAL"
        elif self.az < -0.5:
            return "UPSIDE_DOWN"
        return "TILTED"

class SensorValidationResult(BaseModel):
    sensor_name: str
    status: SensorQualityStatus
    value: Optional[float]
    bounds_min: float
    bounds_max: float
    reason: Optional[str] = None
    age_ms: float = 0.0
    source: SensorDataSource = SensorDataSource.SIMULATED

class EvidenceItem(BaseModel):
    sensor_name: str
    deviation_z: float
    persistence_p: float
    weight: float
    direction: str  # "HIGH", "LOW", "NEUTRAL", "OBSTRUCTION", "CONTRADICTION"
    description: str

class DecisionExplanation(BaseModel):
    timestamp_iso: str
    timestamp_ms: int
    state: SystemState
    risk_score: float = Field(..., ge=0.0, le=100.0)
    confidence: float = Field(..., ge=0.0, le=1.0)
    raw_evidence_score: float
    supporting_evidence: List[EvidenceItem] = []
    contradictory_evidence: List[EvidenceItem] = []
    neutral_evidence: List[EvidenceItem] = []
    sensor_quality_issues: List[SensorValidationResult] = []
    rules_triggered: List[str] = []
    action_requested: ProtectiveAction
    action_executed: bool = True
    is_simulated_action: bool = False
    baseline_version: int = 1
    recovery_attempts: int = 0
    lockout_active: bool = False
    commanded_state: MotorState = MotorState.STOPPED
    inferred_state: MotorState = MotorState.STOPPED

class BaselineStats(BaseModel):
    sensor_name: str
    mean: float
    std_dev: float
    sample_count: int
    min_val: float
    max_val: float
    last_updated_iso: str

class CalibrationProfile(BaseModel):
    version: int
    created_at_iso: str
    sample_count: int
    hold_dwell_seconds: float
    acs712_zero_adc: int = 514
    acs712_sensitivity_v_per_a: float = 0.066
    mpu6050_gravity_z: float = -1.0
    mpu6050_upside_down: bool = True
    ir_active_low: bool = True
    sensors: Dict[str, BaselineStats] = {}
    is_valid: bool = True
    rejection_reason: Optional[str] = None

class FaultInjectionState(BaseModel):
    fault_key: str
    name: str
    description: str
    is_active: bool = False
    injected_at_iso: Optional[str] = None
    parameters: Dict[str, Any] = Field(default_factory=dict)
