def test_serial_manager_ingestion_with_lm35_and_temp_fusion():
    """Verify SerialManager parses frame with LM35 and computes fused temperature"""
    sm = SerialHardwareManager()
    parsed_frames = []
    sm.on_frame_callbacks.append(lambda f: parsed_frames.append(f))

