# 1. Temperature Fusion Unit Tests (Section 5 items 1, 2, 3, 4)
# ------------------------------------------------------------------------------
def test_temp_fusion_both_valid():
    """Case 1: Both LM35 and DHT11 valid -> Arithmetic mean (lm35 + dht) / 2.0"""
    lm35 = 32.4
    dht = 28.0
    fused, valid, source = calculate_temperature_fusion(lm35, dht)
    assert valid is True
    assert source == "FUSED"
    assert fused == pytest.approx(30.2, abs=0.01)


def test_temp_fusion_only_lm35_valid():
    """Case 2: Only LM35 valid -> Single-sensor fallback to LM35"""
    lm35 = 34.6
    dht = None
    fused, valid, source = calculate_temperature_fusion(lm35, dht)
    assert valid is True
    assert source == "LM35"
    assert fused == pytest.approx(34.6, abs=0.01)


def test_temp_fusion_only_dht11_valid():
    """Case 3: Only DHT11 valid -> Single-sensor fallback to DHT11"""
    lm35 = None
    dht = 27.8
    fused, valid, source = calculate_temperature_fusion(lm35, dht)
    assert valid is True
    assert source == "DHT11"
    assert fused == pytest.approx(27.8, abs=0.01)


def test_temp_fusion_both_invalid_not_fabricated():
    """Case 4: Neither sensor valid -> Unavailable (None), not a fabricated zero"""
    lm35 = None
    dht = None
    fused, valid, source = calculate_temperature_fusion(lm35, dht)
    assert valid is False
    assert source == "NONE"
    assert fused is None  # Strictly unavailable, not 0.0


def test_temp_fusion_out_of_bounds_treated_as_invalid():
    """Out-of-bounds readings (e.g. DHT11 -99C or LM35 150C) are treated as invalid"""
    fused, valid, source = calculate_temperature_fusion(lm35_c=31.0, dht_c=-99.0)
    assert valid is True
    assert source == "LM35"
    assert fused == pytest.approx(31.0, abs=0.01)

    fused2, valid2, source2 = calculate_temperature_fusion(lm35_c=180.0, dht_c=26.5)
    assert valid2 is True
    assert source2 == "DHT11"
    assert fused2 == pytest.approx(26.5, abs=0.01)


