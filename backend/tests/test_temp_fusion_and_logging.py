# Helper function for temperature fusion calculation matching firmware & backend
def calculate_temperature_fusion(lm35_c, dht_c):
    lm35_ok = lm35_c is not None and (0.0 <= lm35_c <= 120.0)
    dht_ok = dht_c is not None and (0.0 <= dht_c <= 60.0)

    if lm35_ok and dht_ok:
        return round((lm35_c + dht_c) / 2.0, 2), True, "FUSED"
    elif lm35_ok:
        return round(lm35_c, 2), True, "LM35"
    elif dht_ok:
        return round(dht_c, 2), True, "DHT11"
    else:
        return None, False, "NONE"


